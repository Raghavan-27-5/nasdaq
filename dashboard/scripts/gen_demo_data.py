def gen_models(cal: list[date]) -> dict:
    rng = random.Random(SEED + 7)
    n_folds = 9
    # Walk-forward folds: expanding window, 126d validation, 63d test.
    first_pred = 504  # OOS begins 2022-01
    span = (len(cal) - first_pred) / n_folds

    out: dict[str, dict] = {}
    for key, label, kind, horizon in TARGETS:
        mu, sd, hit, rr, rmse, mae, biter = MODEL_STATS[key]
        folds = []
        for i in range(n_folds):
            te0 = int(first_pred + i * span)
            te1 = int(first_pred + (i + 1) * span)
            va0, va1 = te0 - 126, te0
            tr1 = va0
            tr0 = max(0, int(va0 - 252 * (1 + i * 0.55)))
            folds.append(
                {
                    "fold": i + 1,
                    "train_start": cal[tr0].isoformat(),
                    "train_end": cal[tr1 - 1].isoformat(),
                    "val_start": cal[va0].isoformat(),
                    "val_end": cal[va1 - 1].isoformat(),
                    "test_start": cal[te0].isoformat(),
                    "test_end": cal[te1 - 1].isoformat(),
                    "n_train": max(tr1 - tr0, 0) * 20,
                    "n_val": max(va1 - va0, 0) * 20,
                    "n_test": max(te1 - te0, 0) * 20,
                    "purge_days": horizon,
                    "embargo_days": max(horizon, 5),
                    "best_iter": int(biter * rng.uniform(0.78, 1.24)),
                    "oos_ic": round(mu + rng.gauss(0, sd * 0.22), 4),
                    "oos_r2": round(rr * rng.uniform(0.55, 1.42), 4),
                }
            )

        # Weekly OOS IC series (out-of-sample only, never training rows).
        n_weeks = (len(cal) - first_pred) // 5
        ic_series = []
        for k in range(n_weeks):
            drift = mu * (1.0 + 0.45 * math.sin(k / 11.0))
            ic_series.append(round(drift + rng.gauss(0, sd * 0.62), 4))

        decay = []
