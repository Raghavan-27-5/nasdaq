def gen_market(cal: list[date]) -> dict:
    rng = random.Random(SEED)

    # Broad tech factor, anchored per documented regime. Each segment must
    # continue from the previous segment's endpoint, otherwise every regime
    # boundary injects a discontinuity of tens of percent.
    broad: list[float] = []
    seg_bounds: list[tuple[int, int]] = []
    cursor = 0.0
    for i, (a, b, tot, vol) in enumerate(BROAD_REGIMES):
        da = date.fromisoformat(a)
        db = date.fromisoformat(b)
        lo = next((j for j, d in enumerate(cal) if d >= da), len(cal))
        hi = next((j for j, d in enumerate(cal) if d >= db), len(cal))
        n = max(hi - lo, 1)
        seg_bounds.append((lo, hi))
        path = bridge(rng, n + 1, tot, vol, start=cursor)
        cursor = path[-1]
        broad.extend(path if i == 0 else path[1:])

    if len(broad) < len(cal):
        broad.extend([broad[-1]] * (len(cal) - len(broad)))
    broad = broad[: len(cal)]
    broad_r = diff(broad)
    # Anchor the broad factor on its intended total return, and pin its
    # volatility to BROAD_VOL regardless of what the segment bridges produced.
    broad_r = calibrate(broad_r, BROAD_VOL, sum(s[2] for s in BROAD_REGIMES))

    # Sector factors: broad beta ~0.55 with regime tilts.
    sectors: dict[str, list[tuple[float, float]]] = {
        "SEMI": [],
        "HYPER": [],
        "SOFT": [],
    }
    for si, seg in enumerate(BROAD_REGIMES):
        tot, vol = seg[2], seg[3]
        for sec in sectors:
            sectors[sec].append((tot * 0.55 + SECTOR_TILT[sec][si], vol * 0.72))

    # NOTE: never use hash(str) here. Python randomises string hashing per
    # process, which would silently break the reproducibility contract.
    sec_paths: dict[str, list[float]] = {}
    for off, sec in enumerate(["SEMI", "HYPER", "SOFT"]):
        r = random.Random(SEED + 500 + off * 97)
        lvl: list[float] = [0.0]
        cursor = 0.0
        for si, (tot, vol) in enumerate(sectors[sec]):
            lo, hi = seg_bounds[si]
            path = bridge(r, hi - lo + 1, tot, vol, start=cursor)
            cursor = path[-1]
            lvl.extend(path[1:])
        sec_paths[sec] = lvl[: len(cal)]

    # Hoisted out of the per-ticker loop - diffing a 1.7k series once per day
    # per ticker would be O(n^2) for no reason.
    sec_returns: dict[str, list[float]] = {}
    for sec in ["SEMI", "HYPER", "SOFT"]:
        raw = diff(sec_paths[sec])
        sec_returns[sec] = calibrate(raw, SECTOR_VOL, sum(t for t, _ in sectors[sec]))

    # Per-ticker returns.
    returns: dict[str, list[float]] = {}
    levels: dict[str, list[float]] = {}
    start_idx: dict[str, int] = {}
    realised_vol: dict[str, float] = {}

    for t in TICKERS:
        anchor, lvl22, b, bs, sec, iv, fy, fm = UNIVERSE_CONFIG[t]
        first = date(fy, fm, 1)
        si = next((j for j, d in enumerate(cal) if d >= first), len(cal))
        start_idx[t] = si

        # Collision-free per-ticker seed. An ASCII-sum seed (sum(ord(c))*37)
        # collides - AMZN and PANW both sum to 310, CRWD and QCOM both to 304 -
        # which made those pairs share an identical idiosyncratic shock series
        # and drove their measured correlation above 0.9.
        r = random.Random(SEED + TICKER_SEED[t] * 7919)
        # One return per PRICE OBSERVATION. Using len(cal)-si would give an
        # extra trailing return with no matching date, which silently
        # misaligns every downstream join by one day.
        n = len(cal) - si - 1
        if n < 2:
            returns[t], levels[t] = [], []
            continue

        raw: list[float] = []
        for i in range(1, n + 1):
            g = si + i - 1
            idx = min(max(g - 1, 0), len(broad_r) - 1)
            mkt = broad_r[idx] * b
            sc = sec_returns[sec][g - 1] * bs if g - 1 < len(sec_returns[sec]) else 0.0
            idio = r.gauss(0.0, iv / math.sqrt(252.0))
            raw.append(mkt + sc + idio)

        # Target vol follows from the factor loadings by construction, so the
        # risk numbers the UI reports are consistent with the chart it draws.
        target_vol = math.sqrt((b * BROAD_VOL) ** 2 + (bs * SECTOR_VOL) ** 2 + iv**2)
        daily = calibrate(raw, target_vol, math.log(lvl22 / anchor))

        px = [anchor]
        for x in daily:
            px.append(px[-1] * math.exp(x))
        # Guard the contract: the endpoint must land on the intended level.
        px[-1] = lvl22

        levels[t] = px
        returns[t] = [0.0] + daily
        realised_vol[t] = round(ann_vol(daily), 4)

    # Benchmarks: shape driven by their constituent basket, then calibrated to a
    # realistic benchmark volatility so QQQ/SOXX/SPY read correctly.
    benchmarks: dict[str, dict] = {}
    for bm, comps in [
        (
            "QQQ",
            [
                "NVDA",
                "AVGO",
                "AMD",
                "MU",
                "MSFT",
                "GOOGL",
                "AMZN",
                "META",
                "CRWD",
                "ADBE",
            ],
        ),
        ("SOXX", ["NVDA", "AVGO", "AMD", "MU", "MRVL", "LRCX", "AMAT", "QCOM"]),
        ("SPY", ["MSFT", "GOOGL", "AMZN", "META", "PANW", "CRWD", "ADBE", "DDOG"]),
    ]:
        r = random.Random(SEED + sum(ord(c) for c in bm) * 11)
        sig: list[float] = []
        noise: list[float] = []
        for i in range(1, len(cal)):
            seg = [returns[c][i - start_idx[c]] for c in comps if i >= start_idx[c]]
            sig.append(mean(seg) * 0.86 if seg else 0.0)
            noise.append(r.gauss(0.0, BENCH_VOL[bm] / math.sqrt(252.0)))
        # CRITICAL: 1694 draws of N(0, 0.017) accumulate to a drift with
        # standard deviation ~0.71. Using sum(shape) as the calibration target
        # would let that noise decide the benchmark's final level. De-mean it
        # so the noise adds dispersion only, never drift.
        nm = mean(noise)
        noise = [x - nm for x in noise]
        shape = [a + b for a, b in zip(sig, noise)]
        br = calibrate(shape, BENCH_VOL[bm], sum(sig))
        lvl = [100.0]
        for x in br:
            lvl.append(lvl[-1] * math.exp(x))
        benchmarks[bm] = {
            "levels": [round(v, 4) for v in lvl],
            "returns": br,
            "constituents": comps,
            "realised_vol": round(ann_vol(br), 4),
        }

    return {
        "dates": [d.isoformat() for d in cal],
        "levels": levels,
        "returns": returns,
        "start_idx": start_idx,
        "benchmarks": benchmarks,
        "realised_vol": realised_vol,
    }


