def bridge(
    rng: random.Random, n: int, target_log: float, vol: float, start: float = 0.0
) -> list[float]:
    """
    Brownian bridge from `start` to `start + target_log` over n points.

    The `start` argument is essential when stitching regimes: each segment must
    continue from the previous segment's endpoint. Omitting it restarts every
    segment at zero and injects a spurious ~40% jump at each regime boundary.
    """
    if n < 2:
        return [start] * n
    dt = 1.0 / 252.0
    step = vol * math.sqrt(dt)
    w = [0.0]
    for _ in range(n - 1):
        w.append(w[-1] + rng.gauss(0.0, step))
    for i in range(n):
        t = i / (n - 1)
        w[i] = start + (w[i] - t * w[-1] + t * target_log)
    return w


def diff(x: list[float]) -> list[float]:
    return [x[i] - x[i - 1] for i in range(1, len(x))]


def norm_cdf(x: float) -> float:
    return 0.5 * (1.0 + math.erf(x / math.sqrt(2.0)))


def mean(xs: list[float]) -> float:
    return sum(xs) / len(xs) if xs else 0.0


def std(xs: list[float]) -> float:
    if len(xs) < 2:
        return 0.0
    m = mean(xs)
    return math.sqrt(sum((x - m) ** 2 for x in xs) / (len(xs) - 1))


def corr(a: list[float], b: list[float]) -> float:
    if len(a) < 3:
        return 0.0
    ma, mb = mean(a), mean(b)
    ca = sum((x - ma) * (y - mb) for x, y in zip(a, b))
    va = math.sqrt(sum((x - ma) ** 2 for x in a))
    vb = math.sqrt(sum((y - mb) ** 2 for y in b))
    return ca / (va * vb) if va > 0 and vb > 0 else 0.0


def beta(y: list[float], x: list[float]) -> float:
    if len(y) < 3:
        return 0.0
    mx, my = mean(x), mean(y)
    cov = sum((a - mx) * (b - my) for a, b in zip(x, y))
    var = sum((a - mx) ** 2 for a in x)
    return cov / var if var > 0 else 0.0


def max_drawdown(series: list[float]) -> float:
    peak = series[0]
    mdd = 0.0
    for v in series:
        peak = max(peak, v)
        mdd = min(mdd, (v - peak) / peak)
    return mdd


def quantiles(xs: list[float], qs: list[float]) -> list[float]:
    s = sorted(xs)
    out = []
    for q in qs:
        i = q * (len(s) - 1)
        lo = int(math.floor(i))
        hi = int(math.ceil(i))
        out.append(s[lo] + (s[hi] - s[lo]) * (i - lo))
    return out


def r2(y: list[float], p: list[float]) -> float:
    my = mean(y)
    ss_tot = sum((v - my) ** 2 for v in y)
    ss_res = sum((a - b) ** 2 for a, b in zip(y, p))
    return 1.0 - ss_res / ss_tot if ss_tot > 0 else 0.0


def ann_vol(rets: list[float]) -> float:
    return std(rets) * math.sqrt(252.0)


def calibrate(rets: list[float], target_vol: float, target_total: float) -> list[float]:
    """
    Rescale a log-return path so it (a) hits `target_vol` annualised and
    (b) sums to exactly `target_total`, while preserving the SHAPE that the
    regime bridges gave it.

    Deviation-from-drift is scaled (this sets the volatility), then a constant
    drift correction is added (this sets the endpoint). Doing it in this order
    means the two constraints are independent and neither distorts the other.
    """
    n = len(rets)
    if n == 0:
        return rets
    m = mean(rets)
    dev = [x - m for x in rets]
    rv = ann_vol(dev)
    k = (target_vol / rv) if rv > 1e-12 else 1.0
    dev = [x * k for x in dev]
    drift = (target_total - sum(dev)) / n
    return [x + drift for x in dev]


def align(
    ticker_returns: list[float], start: int, bench_returns: list[float], n_cal: int
) -> tuple[list[float], list[float]]:
    """
    Return (ticker, benchmark) return pairs aligned on CALENDAR DATE.

    Convention: returns[t][k] is the return ARRIVING at calendar index
    start + k; bench_returns[j] is the return arriving at calendar index j + 1.
    Pairing them naively with zip() is off by one day, which is enough to
    attenuate every beta and correlation in the app.
    """
    out_t: list[float] = []
    out_b: list[float] = []
    for c in range(max(start, 1), n_cal):
        out_t.append(ticker_returns[c - start])
        out_b.append(bench_returns[c - 1])
    return out_t, out_b


def invert(mat: list[list[float]]) -> list[list[float]]:
    """Gauss-Jordan inverse for small dense matrices (used for OLS SEs)."""
    n = len(mat)
    a = [
        row[:] + [1.0 if i == j else 0.0 for j in range(n)] for i, row in enumerate(mat)
    ]
    for col in range(n):
        piv = max(range(col, n), key=lambda r: abs(a[r][col]))
        if abs(a[piv][col]) < 1e-18:
            raise ValueError("singular matrix")
        a[col], a[piv] = a[piv], a[col]
        d = a[col][col]
        a[col] = [v / d for v in a[col]]
        for r in range(n):
            if r != col:
                f = a[r][col]
                if f:
                    a[r] = [v - f * w for v, w in zip(a[r], a[col])]
    return [row[n:] for row in a]


