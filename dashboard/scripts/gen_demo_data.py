def gen_backtest(mk: dict, universe: list[dict], port: dict) -> dict:
    cal = mk["dates"]
    n = len(cal)
    tickers = [c["ticker"] for c in universe]

    # Equal-weight universe benchmark, buy-and-hold over tradable names.
    ew = [100.0]
    for i in range(1, n):
        rets = []
        for t in tickers:
            si = mk["start_idx"][t]
            if i >= si:
                rets.append(mk["returns"][t][i - si])
        ew.append(ew[-1] * math.exp(mean(rets)))

    # ML portfolio: correlated with EW but with a modest, explicitly-derived tilt.
    rng = random.Random(SEED + 33)
    ew_r = diff([math.log(v) for v in ew])
    ml_r = []
    for i in range(len(ew_r)):
        ml_r.append(ew_r[i] * 0.82 + rng.gauss(0.0, 0.0042))

    ml = [100.0]
    for x in ml_r:
        ml.append(ml[-1] * math.exp(x))

    series = {
        "ML_PORTFOLIO": [round(v, 3) for v in ml],
        "EW_UNIVERSE": [round(v, 3) for v in ew],
        "QQQ": [round(v, 3) for v in mk["benchmarks"]["QQQ"]["levels"]],
        "SOXX": [round(v, 3) for v in mk["benchmarks"]["SOXX"]["levels"]],
        "SPY": [round(v, 3) for v in mk["benchmarks"]["SPY"]["levels"]],
    }

    years = sorted({d[:4] for d in cal})
    yr_rows = []
    for y in years:
        idx = [i for i, d in enumerate(cal) if d[:4] == y]
        if len(idx) < 20:
            continue
        row = {"year": y, "days": len(idx)}
        for k, v in series.items():
            a, b = v[idx[0]], v[idx[-1]]
            row[k] = round((b / a - 1) * 100, 2)
        yr_rows.append(row)

    # Factor attribution on the ML portfolio (OLS vs factors).
    ml_logr = diff([math.log(v) for v in ml])
    qqq = mk["benchmarks"]["QQQ"]["returns"][1:]
    soxx = mk["benchmarks"]["SOXX"]["returns"][1:]
    L = min(len(ml_logr), len(qqq), len(soxx))
    y = ml_logr[-L:]
    X = [[1.0, qqq[-L:][i], soxx[-L:][i]] for i in range(L)]
    k = 3
    XtX = [
        [sum(X[i][a] * X[i][b] for i in range(L)) for b in range(k)] for a in range(k)
    ]
    Xty = [sum(X[i][a] * y[i] for i in range(L)) for a in range(k)]
    for i in range(k):  # gaussian elimination
        p = max(range(i, k), key=lambda r: abs(XtX[r][i]))
        XtX[i], XtX[p] = XtX[p], XtX[i]
        Xty[i], Xty[p] = Xty[p], Xty[i]
        for r in range(i + 1, k):
            f = XtX[r][i] / XtX[i][i]
            for c in range(i, k):
                XtX[r][c] -= f * XtX[i][c]
            Xty[r] -= f * Xty[i]
    beta_v = [0.0] * k
    for i in reversed(range(k)):
        s = Xty[i] - sum(XtX[i][j] * beta_v[j] for j in range(i + 1, k))
        beta_v[i] = s / XtX[i][i]

    resid = [y[i] - sum(beta_v[j] * X[i][j] for j in range(k)) for i in range(L)]
    fit = [y[i] - resid[i] for i in range(L)]
    r2v = 1 - sum(r * r for r in resid) / sum((v - mean(y)) ** 2 for v in y)
    n_free = L - k
    # Residual variance of the regression.
    se2 = max(sum(r * r for r in resid) / n_free, 1e-12)

    # Var(beta) = sigma^2 * (X'X)^-1. Invert the full 3x3 rather than trying
    # to shortcut the cofactor algebra - this is exact and easy to audit.
    try:
        xtx_inv = invert(XtX)
        se_beta = [math.sqrt(se2 * xtx_inv[j][j]) for j in range(k)]
    except ValueError:
        se_beta = [float("nan")] * k

    names = [
        "Intercept (annualised alpha)",
        "QQQ / Nasdaq-100",
        "SOXX / Semiconductors",
    ]
    att = []
    for j in range(k):
        se_j = se_beta[j] if se_beta[j] > 0 else float("nan")
        t = beta_v[j] / se_j if se_j == se_j and se_j > 0 else float("nan")
        att.append(
            {
                "factor": names[j],
                # Intercept is reported annualised, slopes are unitless betas.
                "coef": round(beta_v[j] * 252, 4) if j == 0 else round(beta_v[j], 3),
                "tstat": None if t != t else round(t, 2),
                "annualised": j == 0,
            }
        )

    def perf(v: list[float]) -> dict:
        r = diff([math.log(x) for x in v])
        yrs = (n - 1) / 252.0
        cagr = (v[-1] / v[0]) ** (1 / yrs) - 1
        vol = std(r) * math.sqrt(252)
        dn = [min(x, 0.0) for x in r]
        srt = std(dn) * math.sqrt(252)
        return {
            "cagr": round(cagr, 4),
            "vol": round(vol, 4),
            "sharpe": round(cagr / vol, 3) if vol > 0 else 0.0,
            "sortino": round(cagr / srt, 3) if srt > 0 else 0.0,
            "max_dd": round(max_drawdown(v), 4),
            "worst_30d": round(
                min(
                    quantiles([sum(r[i : i + 21]) for i in range(len(r) - 21)], [0.0])[
                        0
                    ],
                    0,
                ),
                4,
            ),
            "final": round(v[-1], 2),
        }

    return {
        "oos_start": "2022-01-03",
        "oos_end": cal[-1],
        "rebalance": "Monthly (last trading day)",
        "cost_bps_round_trip": 10,
        "series": series,
        "performance": {k: perf(v) for k, v in series.items()},
        "yearly": yr_rows,
        "attribution": {
            "method": "OLS on daily log returns vs QQQ and SOXX",
            "observations": L,
            "r_squared": round(r2v, 4),
            "factors": att,
            "residual_alpha_daily": round(beta_v[0], 6),
            "residual_vol_annual": round(std(resid) * math.sqrt(252), 4),
            "note": "Residual alpha is small relative to its standard error. It is NOT evidence of standalone skill.",
        },
    }


