def easter(year: int) -> date:
    """Anonymous Gregorian algorithm."""
    a = year % 19
    b, c = divmod(year, 100)
    d, e = divmod(b, 4)
    f = (b + 8) // 25
    g = (b - f + 1) // 3
    h = (19 * a + b - d - g + 15) % 30
    i, k = divmod(c, 4)
    l = (32 + 2 * e + 2 * i - h - k) % 7
    m = (a + 11 * h + 22 * l) // 451
    month, day = divmod(h + l - 7 * m + 114, 31)
    return date(year, month, day + 1)


def nth_weekday(year: int, month: int, weekday: int, n: int) -> date:
    d = date(year, month, 1)
    delta = (weekday - d.weekday()) % 7
    return d + timedelta(days=delta + 7 * (n - 1))


def last_weekday(year: int, month: int, weekday: int) -> date:
    d = (
        date(year, month + 1, 1) - timedelta(days=1)
        if month < 12
        else date(year, 12, 31)
    )
    return d - timedelta(days=(d.weekday() - weekday) % 7)


def observed(d: date) -> date:
    """NYSE convention: Sunday holiday -> Monday, Saturday -> Friday."""
    if d.weekday() == 6:
        return d + timedelta(days=1)
    if d.weekday() == 5:
        return d - timedelta(days=1)
    return d


def market_holidays(y: int) -> set[date]:
    return {
        observed(date(y, 1, 1)),
        nth_weekday(y, 1, 0, 3),
        nth_weekday(y, 2, 0, 3),
        easter(y) - timedelta(days=2),
        last_weekday(y, 5, 0),
        observed(date(y, 7, 4)),
        nth_weekday(y, 9, 0, 1),
        nth_weekday(y, 11, 3, 4),
        observed(date(y, 12, 25)),
    }


def build_calendar() -> list[date]:
    days: list[date] = []
    y = START.year
    while y <= END.year:
        hol = market_holidays(y)
        d = date(y, 1, 1)
        while d.year == y:
            if d.weekday() < 5 and d not in hol and START <= d <= END:
                days.append(d)
            d += timedelta(days=1)
        y += 1
    return days


